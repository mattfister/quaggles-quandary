ORIGINALS = "lab2 backup/levels"


def original(name):
    """Floors of an original level, cropped to its used area."""
    floors = []
    f = 0
    while os.path.exists(f"{ORIGINALS}/{name}/{f}.map"):
        with open(f"{ORIGINALS}/{name}/{f}.map") as fh:
            rows = [r.rstrip() for r in fh.read().replace("\r", "").split("\n")]
        while rows and not rows[-1]:
            rows.pop()
        floors.append(rows)
        f += 1
    return floors


