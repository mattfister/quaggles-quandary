def q(s):
    return json.dumps(s, ensure_ascii=False)


# Same layout as Levels.to_json() in scripts/levels.gd, so the editor's saves
# diff cleanly against this.
def emit_level(level, t):
    level_id, title, hint, floors, *stack = level
    out = [t + "{",
           f'{t}\t"id": {q(level_id)}, "title": {q(title)},',
           f'{t}\t"hint": {q(hint)},']
    if stack and stack[0] > 1:
        out.append(f'{t}\t"stack": {stack[0]},')
    out.append(f'{t}\t"floors": [')
    floor_texts = []
    for rows in floors:
        if not rows:
            floor_texts.append(f"{t}\t\t[]")
            continue
        body = ",\n".join(f"{t}\t\t\t{q(r)}" for r in rows)
        floor_texts.append(f"{t}\t\t[\n{body}\n{t}\t\t]")
    out.append(",\n".join(floor_texts))
    out.append(f"{t}\t]")
    out.append(t + "}")
    return "\n".join(out)


def emit_all():
    sets = []
    for set_id, title, label, levels in SET_INFO:
        body = ",\n".join(emit_level(level, "\t\t\t\t") for level in levels)
        sets.append("\t\t{\n"
                    f'\t\t\t"id": {q(set_id)}, "title": {q(title)}, "label": {q(label)},\n'
                    '\t\t\t"levels": [\n' + body + "\n\t\t\t]\n\t\t}")
    return '{\n\t"sets": [\n' + ",\n".join(sets) + "\n\t]\n}\n"


if __name__ == "__main__":
    if os.path.exists("levels/levels.json") and "--force" not in sys.argv:
        sys.exit("levels/levels.json exists and may hold level editor changes; pass --force to overwrite it")
    ids = [level[0] for *_, levels in SET_INFO for level in levels]
    assert len(ids) == len(set(ids)), "duplicate level id"
    os.makedirs("levels", exist_ok=True)
    with open("levels/levels.json", "w", newline="\n", encoding="utf-8") as fh:
        fh.write(emit_all())
    print(", ".join(f"{len(levels)} {set_id}" for set_id, _, _, levels in SET_INFO) + " levels written")
