"""LEGACY: one-time migration of the levels into levels/levels.json.

The levels now live in levels/levels.json, which the in-game level editor
(main menu > Level Editor, when run from the Godot editor) reads and writes.
Rerunning this would throw away everything done in the editor since, so it
refuses to unless given --force.

Levels were defined here as rows of text, one list per floor (bottom floor
first). The 2007 originals are read from "lab2 backup".

Each level is (id, title, hint, floors) or (id, title, hint, floors, stack),
where `stack` is the tallest stack of quaggles the level cannot be won
without; `tests/test_rules.gd -- solve` checks that.

Cells:  . floor   * wall   w glass   x ice   X fire   2 key   3 force field
        4 cracked tile   u lift   g goal   s / 1 quaggle start   (space) nothing

Run from the project root:  python tools/build_levels.py --force
"""
import json
